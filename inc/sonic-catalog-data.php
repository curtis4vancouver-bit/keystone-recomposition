function keystone_get_album_by_id( int $id ): ?array {
    foreach ( keystone_get_all_albums() as $album ) {
        if ( (int) $album['id'] === $id ) {
            return $album;
        }
    }
    return null;
}

/**
 * Retrieve album by UPC barcode.
 */
function keystone_get_album_by_upc( string $upc ): ?array {
    foreach ( keystone_get_all_albums() as $album ) {
        if ( $album['upc'] === $upc ) {
            return $album;
        }
    }
    return null;
}

/**
 * Total count of registered tracks.
 */
function keystone_get_total_tracks_count(): int {
    $total = 0;
    foreach ( keystone_get_all_albums() as $album ) {
        $total += isset( $album['track_count'] ) ? (int) $album['track_count'] : count( $album['tracks'] ?? array() );
    }
    return $total > 0 ? $total : 246;
}

/**
 * Dynamic Catalog Metrics & Synchronization Helper.
 * Returns exact counts across 25 official releases and 23 studio albums.
 *
 * @return array<string, mixed>
 */
function keystone_get_catalog_stats(): array {
    $albums         = keystone_get_all_albums();
    $total_releases = count( $albums );
    $studio_albums  = 0;
    $singles        = 0;
    $total_tracks   = 0;

    foreach ( $albums as $album ) {
        $track_count   = isset( $album['track_count'] ) ? (int) $album['track_count'] : count( $album['tracks'] ?? array() );
        $total_tracks += $track_count;
        if ( $track_count <= 2 ) {
            $singles++;
        } else {
            $studio_albums++;
        }
    }

    return array(
        'total_releases' => $total_releases,
        'studio_albums'  => $studio_albums,
        'singles'        => $singles,
        'total_tracks'   => $total_tracks,
        'display_label'  => sprintf( '%d Official Releases • %d Studio Albums • %d Registered Tracks', $total_releases, $studio_albums, $total_tracks ),
        'short_label'    => $total_releases . ' Releases',
    );
}
